#!/usr/bin/env python3
"""Regenerate the fluid type + space scale in tokens.css:  python3 scripts/type_scale.py

One modular scale drives every text size and every vertical space on the site.
Each step n is  base × ratio^n , and both the base and the ratio grow with the window:

  small end:  base = SMALL_BASE,  ratio = SMALL_RATIO
  large end:  base = LARGE_BASE,  ratio = LARGE_RATIO
  in between: each step slides linearly

The scale is worked out twice — once from the window WIDTH (SMALL_WIDTH → LARGE_WIDTH)
and once from the window HEIGHT (SMALL_HEIGHT → LARGE_HEIGHT) — and each step uses
whichever is smaller. Wide-but-short windows (laptops) therefore shrink the whole
system in proportion, so the page fits without scrolling.

The width defaults reproduce lifeofpai.com: body clamp(1rem, 1.5vw, 1.5rem),
headline clamp(2.5rem, 5.5vw, 6rem) — headline = body × 1.414⁴ on big screens and
≈ body × 1.257⁴ on small ones. The height range was tuned in the browser so the
tallest name font, both columns and the clue fit at 1920×963, 1536×730, 1440×789,
1366×657 and 1280×640.
Edit the numbers below and re-run.
"""
import re
from pathlib import Path

SMALL_WIDTH, LARGE_WIDTH = 720, 1760         # px of window width
SMALL_HEIGHT, LARGE_HEIGHT = 480, 1130       # px of window height (lower = more room)
SMALL_BASE, LARGE_BASE = 16, 24              # px — step 0 (body) at each end
SMALL_RATIO = (40 / 16) ** 0.25              # 1.2574 → step 4 = 40px  (2.5rem)
LARGE_RATIO = 2 ** 0.5                       # 1.4142 → step 4 = 96px  (6rem), augmented fourth
STEPS = range(-1, 6)

TOKENS = Path(__file__).resolve().parent.parent / "tokens.css"
START, END = "/* scale:start", "/* scale:end */"


def num(x):
    return f"{x:.4f}".rstrip("0").rstrip(".")


def rem(px):
    return num(px / 16) + "rem"


def fluid(lo, hi, small, large, unit):
    slope = (hi - lo) / (large - small)          # px per px of viewport
    intercept = lo - slope * small               # px
    v = num(slope * 100) + unit
    expr = f"{rem(intercept)} + {v}" if intercept >= 0 else f"{v} - {rem(-intercept)}"
    return f"clamp({rem(lo)}, {expr}, {rem(hi)})"


def step(n):
    lo, hi = SMALL_BASE * SMALL_RATIO ** n, LARGE_BASE * LARGE_RATIO ** n
    name = f"--step-{n}" if n >= 0 else f"--step-minus-{-n}"
    by_width = fluid(lo, hi, SMALL_WIDTH, LARGE_WIDTH, "vw")
    by_height = fluid(lo, hi, SMALL_HEIGHT, LARGE_HEIGHT, "vh")
    return f"  /* {lo:5.1f} → {hi:5.1f}px */\n  {name}: min({by_width}, {by_height});"


block = "\n".join([
    f"{START} — generated by scripts/type_scale.py; edit the numbers there, not here */",
    f"  /* base {SMALL_BASE}px × {SMALL_RATIO:.4f}^n  →  base {LARGE_BASE}px × {LARGE_RATIO:.4f}^n, "
    f"across width {SMALL_WIDTH}→{LARGE_WIDTH}px and height {SMALL_HEIGHT}→{LARGE_HEIGHT}px "
    "(the smaller result wins) */",
    *[step(n) for n in STEPS],
    f"  {END}",
])

css = TOKENS.read_text(encoding="utf-8")
pattern = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
if not pattern.search(css):
    raise SystemExit(f"tokens.css has no {START} … {END} block to replace")
TOKENS.write_text(pattern.sub(lambda _: block.lstrip(), css, count=1), encoding="utf-8")
print(block)
