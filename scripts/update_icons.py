#!/usr/bin/env python3
"""Rebuild assets/phosphor-icons.svg from the icons named in themes.csv.

Run this after changing any icon_a / icon_b value in themes.csv:

    python3 scripts/update_icons.py              # regular weight (default)
    python3 scripts/update_icons.py --weight light

Icons are downloaded from the official @phosphor-icons/core package (version pinned in
sitedata.py) and packed into one small SVG sprite that only holds the icons the site uses.
The sprite is committed, so the live site never depends on an icon CDN.
"""
import argparse
import re
import sys
import urllib.request

from sitedata import PHOSPHOR_VERSION, ROOT, SPRITE, SPRITE_REF, sprite_ref, used_icons

FAVICON = ("pen-nib", "fill")   # Phosphor icon + weight for the browser-tab icon

WEIGHTS = ["thin", "light", "regular", "bold", "fill", "duotone"]


def fetch(name, weight):
    suffix = "" if weight == "regular" else f"-{weight}"
    url = (f"https://cdn.jsdelivr.net/npm/@phosphor-icons/core@{PHOSPHOR_VERSION}"
           f"/assets/{weight}/{name}{suffix}.svg")
    with urllib.request.urlopen(url, timeout=20) as res:
        return res.read().decode("utf-8")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--weight", default="regular", choices=WEIGHTS)
    weight = parser.parse_args().weight

    symbols, missing = [], []
    for name in used_icons():
        try:
            svg = fetch(name, weight)
        except Exception as err:  # 404 = not a Phosphor icon name
            missing.append(f"{name} ({err})")
            continue
        inner = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S).group(1).strip()
        symbols.append(f'  <symbol id="ph-{name}" viewBox="0 0 256 256">{inner}</symbol>')

    if missing:
        sys.exit("Not found in @phosphor-icons/core " + PHOSPHOR_VERSION + ":\n  " + "\n  ".join(missing))

    SPRITE.parent.mkdir(parents=True, exist_ok=True)
    SPRITE.write_text(
        f"<!-- Generated by scripts/update_icons.py from @phosphor-icons/core@{PHOSPHOR_VERSION} "
        f"({weight} weight, MIT license). Do not edit by hand. -->\n"
        '<svg xmlns="http://www.w3.org/2000/svg" style="display:none">\n'
        + "\n".join(symbols) + "\n</svg>\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(symbols)} {weight} icons to {SPRITE.relative_to(SPRITE.parent.parent)}")

    # Stamp the sprite's new version into index.html so browsers don't keep showing old icons.
    page = ROOT / "index.html"
    html = page.read_text(encoding="utf-8")
    if not SPRITE_REF.search(html):
        sys.exit("index.html: could not find the ICON_SPRITE line to update")
    page.write_text(SPRITE_REF.sub(sprite_ref(), html, count=1), encoding="utf-8")
    print(f"Updated index.html → {sprite_ref().split(chr(39))[1]}")

    # Favicon: dark icon on light browser tabs, light icon on dark tabs.
    name, fav_weight = FAVICON
    inner = re.search(r"<svg[^>]*>(.*)</svg>", fetch(name, fav_weight), re.S).group(1).strip()
    (ROOT / "assets" / "favicon.svg").write_text(
        f"<!-- {name} ({fav_weight}) from @phosphor-icons/core@{PHOSPHOR_VERSION}, MIT. "
        "Generated by scripts/update_icons.py. -->\n"
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256">'
        "<style>path{fill:#111}@media (prefers-color-scheme:dark){path{fill:#fff}}</style>"
        f"{inner}</svg>\n",
        encoding="utf-8",
    )
    print(f"Wrote favicon assets/favicon.svg ({name}, {fav_weight})")


if __name__ == "__main__":
    main()
